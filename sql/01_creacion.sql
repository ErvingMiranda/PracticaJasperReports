-- Crear la base de datos.
CREATE DATABASE bd_renta_casas
    WITH ENCODING 'UTF8'
    TEMPLATE template0;

-- Conectarse a bd_renta_casas antes de continuar.

-- Crear el esquema.
CREATE SCHEMA IF NOT EXISTS inmobiliaria;

-- Crear la tabla de clientes.
CREATE TABLE IF NOT EXISTS inmobiliaria.clientes (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    identificacion VARCHAR(30) NOT NULL UNIQUE,
    telefono VARCHAR(20) NOT NULL,
    correo VARCHAR(120) UNIQUE,
    fecha_registro DATE NOT NULL DEFAULT CURRENT_DATE,

    CONSTRAINT chk_nombres CHECK (LENGTH(nombres) >= 2),
    CONSTRAINT chk_apellidos CHECK (LENGTH(apellidos) >= 2)
    );

-- Crear la tabla de casas.
CREATE TABLE IF NOT EXISTS inmobiliaria.casas (
    id_casa BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(15) NOT NULL UNIQUE,
    direccion VARCHAR(180) NOT NULL,
    ciudad VARCHAR(80) NOT NULL,
    habitaciones INTEGER NOT NULL,
    banos INTEGER NOT NULL,
    precio_mensual NUMERIC(12, 2) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE',

    CONSTRAINT chk_habitaciones CHECK (habitaciones >= 1),
    CONSTRAINT chk_banos CHECK (banos >= 1),
    CONSTRAINT chk_precio_mensual CHECK (precio_mensual > 0),
    CONSTRAINT chk_estado_casa CHECK (estado IN ('DISPONIBLE', 'MANTENIMIENTO', 'INACTIVA'))
    );

-- Crear la tabla de rentas.
CREATE TABLE IF NOT EXISTS inmobiliaria.rentas (
    id_renta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_casa BIGINT NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    precio_mensual_acordado NUMERIC(12, 2) NOT NULL,
    deposito NUMERIC(12, 2) NOT NULL DEFAULT 0,
    estado VARCHAR(15) NOT NULL DEFAULT 'ACTIVA',
    observaciones VARCHAR(250),

    CONSTRAINT chk_fechas CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT chk_precio_acordado CHECK (precio_mensual_acordado > 0),
    CONSTRAINT chk_deposito CHECK (deposito >= 0),
    CONSTRAINT chk_estado_renta CHECK (estado IN ('ACTIVA', 'FINALIZADA', 'CANCELADA')),

    CONSTRAINT fk_renta_cliente
    FOREIGN KEY (id_cliente) REFERENCES inmobiliaria.clientes(id_cliente),
    CONSTRAINT fk_renta_casa
    FOREIGN KEY (id_casa) REFERENCES inmobiliaria.casas(id_casa)
    );